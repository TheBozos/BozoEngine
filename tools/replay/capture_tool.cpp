// bozo-capture-tool: what the replay build needs from a set of captures before any code is generated.
//
//   bozo-capture-tool externals <out file> <capture folder or root>...
//       The addresses the runtime answers (docs/specs/replay.md): "stub 0xADDR" for every kind 1 out-call target,
//       "override 0xADDR" for every kind 2 target and every address of an OVRD list. A root folder is searched for
//       capture.bin files one level down. The file is rewritten only when its contents change.
//   bozo-capture-tool hash <file>
//       XXH64 (seed 0) of a file, as the captures' header holds the game ELF's.
#include "capture.h"

#include <algorithm>
#include <cstdio>
#include <cstring>
#include <filesystem>
#include <format>
#include <fstream>
#include <iterator>
#include <map>
#include <set>
#include <string>
#include <vector>

using namespace bozo::capture;
namespace fs = std::filesystem;

namespace
{
    std::vector<std::string> captureFiles(const std::vector<std::string> &args)
    {
        std::vector<std::string> out;
        for (const std::string &a : args)
        {
            if (fs::is_regular_file(a))
                out.push_back(a);
            else if (fs::is_regular_file(fs::path(a) / "capture.bin"))
                out.push_back((fs::path(a) / "capture.bin").string());
            else if (fs::is_directory(a))
            {
                std::vector<std::string> sub;
                for (const auto &e : fs::directory_iterator(a))
                    if (e.is_directory() && fs::is_regular_file(e.path() / "capture.bin"))
                        sub.push_back((e.path() / "capture.bin").string());
                std::sort(sub.begin(), sub.end());
                out.insert(out.end(), sub.begin(), sub.end());
            }
        }
        return out;
    }

    int externals(const std::string &outPath, const std::vector<std::string> &inputs)
    {
        std::set<uint32_t> stubs, overrides;
        const auto files = captureFiles(inputs);
        if (files.empty())
        {
            std::fprintf(stderr, "bozo-capture-tool: no capture found\n");
            return 1;
        }
        uint64_t samples = 0;
        for (const std::string &f : files)
        {
            Reader r;
            if (!r.open(f))
            {
                std::fprintf(stderr, "bozo-capture-tool: %s\n", r.error().c_str());
                return 1;
            }
            Chunk c;
            while (r.next(c))
            {
                const std::string tag = c.tag;
                if (tag == "SAMP")
                {
                    Sample s;
                    std::string error;
                    if (!parseSample(std::move(c.data), s, error))
                    {
                        std::fprintf(stderr, "bozo-capture-tool: %s: %s\n", f.c_str(), error.c_str());
                        return 1;
                    }
                    ++samples;
                    for (const Outcall &o : s.outcalls)
                        if (o.kind == kStub)
                            stubs.insert(o.target);
                        else if (o.kind == kOverride)
                            overrides.insert(o.target);
                }
                else if (tag == "OVRD" && c.data.size() >= 4)
                {
                    uint32_t n;
                    std::memcpy(&n, c.data.data(), 4);
                    for (uint32_t k = 0; k < n && 4 + 4 * (k + 1) <= c.data.size(); ++k)
                    {
                        uint32_t a;
                        std::memcpy(&a, c.data.data() + 4 + 4 * k, 4);
                        overrides.insert(a);
                    }
                }
            }
            if (!r.error().empty())
            {
                std::fprintf(stderr, "bozo-capture-tool: %s\n", r.error().c_str());
                return 1;
            }
        }
        std::string text = std::format("# Generated by bozo-capture-tool from {} captures ({} samples). Do not edit.\n",
                                       files.size(), samples);
        for (uint32_t a : stubs)
            text += std::format("stub 0x{:x}\n", a);
        for (uint32_t a : overrides)
            if (!stubs.count(a))
                text += std::format("override 0x{:x}\n", a);
        {
            std::ifstream in(outPath, std::ios::binary);
            std::string old((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
            if (old == text)
            {
                std::printf("externals: %zu stubs, %zu overrides (unchanged)\n", stubs.size(), overrides.size());
                return 0;
            }
        }
        std::ofstream o(outPath, std::ios::binary);
        o << text;
        if (!o)
        {
            std::fprintf(stderr, "bozo-capture-tool: cannot write %s\n", outPath.c_str());
            return 1;
        }
        std::printf("externals: %zu stubs, %zu overrides, written to %s\n", stubs.size(), overrides.size(), outPath.c_str());
        return 0;
    }
}

int main(int argc, char **argv)
{
    if (argc >= 4 && std::strcmp(argv[1], "externals") == 0)
        return externals(argv[2], std::vector<std::string>(argv + 3, argv + argc));
    if (argc == 3 && std::strcmp(argv[1], "hash") == 0)
    {
        uint64_t h = 0;
        if (!hashFile(argv[2], h))
        {
            std::fprintf(stderr, "bozo-capture-tool: cannot read %s\n", argv[2]);
            return 1;
        }
        std::printf("%016llx  %s\n", static_cast<unsigned long long>(h), argv[2]);
        return 0;
    }
    std::fprintf(stderr, "usage: bozo-capture-tool externals <out file> <capture folder or root>...\n"
                         "       bozo-capture-tool hash <file>\n");
    return 2;
}
